"""Offline eta-tail references from mpmath differentiation of the defining density."""
from __future__ import annotations
from pathlib import Path
import mpmath as mp


def normalizer(e):
    if e == 0:
        return -mp.log(2*mp.pi)/2
    if abs(e) < mp.mpf('0.001'):
        rho = sum((1-2**(2*m))*mp.bernoulli(2*m)*e**(2*m-1)/(2*m*(2*m-1)) for m in range(1,25))
        return -mp.log(2*mp.pi)/2-mp.log1p(-2*e)/2+rho
    return mp.loggamma((1+e)/(2*e))-mp.loggamma(1/(2*e))-mp.log(mp.pi*(1-2*e)/e)/2


def kernel(u,e):
    return (1+e)/(2*e)*mp.log1p(u*u*e/(1-2*e))


def main():
    mp.mp.dps=110
    output=['// Generated by student_reference.py at 110 decimal digits.', 'constexpr TailReference tail_references[] = {']
    for e0 in [0.,1e-300,1e-16,1e-10,1e-6,1e-3,.1,.12,.2,.3,.49]:
        e=mp.mpf(e0)
        if e0<1e-100:
            norm=[-mp.log(2*mp.pi)/2,mp.mpf(3)/4,mp.mpf(2)]
        else:norm=[normalizer(e),mp.diff(normalizer,e),mp.diff(normalizer,e,2)]
        for u0 in [0.,1e-6,.1,.5,1.,3.,10.,1e3,1e6]:
            u=mp.mpf(u0)
            if e0<1e-100:
                values=[u*u/2,u,mp.mpf(1),3*u*u/2-u**4/4,3*u-u**3,6*u*u-mp.mpf(5)/2*u**4+u**6/3]
            else:
                values=[kernel(u,e),mp.diff(lambda v:kernel(v,e),u),mp.diff(lambda v:kernel(v,e),u,2),mp.diff(lambda v:kernel(u,v),e),mp.diff(kernel,(u,e),(1,1)),mp.diff(lambda v:kernel(u,v),e,2)]
            output.append('    {'+format(e0,'.17g')+', '+format(u0,'.17g')+', {'+', '.join(format(float(v),'.17g') for v in values+norm)+'}},')
    output.append('};')
    output.append('constexpr SkewReference skew_references[] = {')
    for e0 in [0.,1e-300,1e-16,1e-10,1e-6,1e-3,.1,.3,.49]:
        e,lam=mp.mpf(e0),mp.mpf(.3)
        def a(e,l): return 4*l*mp.exp(normalizer(e))*(1-2*e)/(1-e)
        def b(e,l): return mp.sqrt(1+3*l*l-a(e,l)**2)
        values=[a(e,lam),b(e,lam)]
        for f in [a,b]:
            values += [mp.diff(f,(e,lam),(1,0)),mp.diff(f,(e,lam),(0,1))]
        for f in [a,b]:
            values += [mp.diff(f,(e,lam),(2,0)),mp.diff(f,(e,lam),(1,1)),mp.diff(f,(e,lam),(0,2))]
        values[8]=mp.mpf(0)  # a is linear in lambda.
        output.append('    {'+format(e0,'.17g')+', {'+', '.join(format(float(v),'.17g') for v in values)+'}},')
    output.append('};')
    output.append('constexpr ProbabilityReference probability_references[] = {')
    for e0 in [0.,1e-300,1e-16,1e-10,1e-6,1e-3,.1,.3,.49,float.fromhex("0x1.fffffffffffffp-2")]:
        e=mp.mpf(e0)
        for z0 in [.1,2.,8.,20.]:
            z=mp.mpf(z0)
            if e0<1e-100:tail=mp.erfc(z/mp.sqrt(2))/2
            elif e0<1e-3:
                tail=mp.quad(lambda u:mp.exp(normalizer(e)-kernel(u,e)),[z,z+1,z+10,mp.inf])
            else:tail=mp.betainc(1/(2*e),mp.mpf('.5'),0,(1-2*e)/(1-2*e+e*z*z),regularized=True)/2
            output.append('    {'+format(e0,'.17g')+', '+format(z0,'.17g')+', '+format(float(tail),'.17g')+'},')
    output.append('};\n')
    Path(__file__).with_suffix('.inc').write_text('\n'.join(output))

if __name__=='__main__':main()
