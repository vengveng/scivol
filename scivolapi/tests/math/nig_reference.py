"""Fixed-order Bessel references from mpmath, including all finite argument scales."""
from __future__ import annotations

import argparse
import math
from pathlib import Path

import mpmath as mp


def reference(z: float) -> list[mp.mpf]:
    with mp.workdps(max(90, 90 + 2 * int(abs(math.log10(z))))):
        x = mp.mpf(z)
        k0, k1 = mp.besselk(0, x), mp.besselk(1, x)
        ratio = k0 / k1
        return [mp.log(mp.exp(x) * k1) - mp.log(x),
                1 - ratio - 2 / x, 1 - ratio / x - ratio * ratio + 2 / (x * x)]


def coefficients() -> None:
    mp.mp.dps = 110
    degree = 8
    nodes = [(1 - mp.cos(mp.pi * k / (2 * degree))) / 2 for k in range(2 * degree + 1)]
    values = [mp.exp(2/x) * mp.sqrt(4/(mp.pi*x)) * mp.besselk(1, 2/x) if x else mp.mpf(1)
              for x in nodes]
    matrix = mp.matrix([[x**j for j in range(degree + 1)] + [-y * x**j for j in range(1, degree + 1)]
                        for x, y in zip(nodes, values)])
    solution = mp.lu_solve(matrix, mp.matrix(values))
    arrays = {'k1_numerator': list(solution[:degree + 1]),
              'k1_denominator': [mp.mpf(1)] + list(solution[degree + 1:])}
    arrays.update({name: [function(k) for k in range(17)] for name, function in (
        ('k0_small', lambda k: (mp.harmonic(k) - mp.euler) / mp.factorial(k)**2),
        ('k1_small', lambda k: (1 - 2*k*(mp.harmonic(k) - mp.euler)) / mp.factorial(k)**2),
        ('i0_small', lambda k: 1 / mp.factorial(k)**2),
        ('zi1_small', lambda k: 2*k / mp.factorial(k)**2),
    )})
    for name, values in arrays.items():
        print('constexpr double ' + name + '[] = {')
        for value in values:
            print('    ' + mp.nstr(value, 26) + ',')
        print('};')


def main() -> None:
    points = {math.ulp(0.0), math.nextafter(2.0, 0.0), math.nextafter(2.0, math.inf),
              float.fromhex('0x1.fffffffffffffp+1023')}
    points.update(2 * k / 100 for k in range(1, 101))
    points.update(2 * 10 ** (k / 40) for k in range(201))
    points.update(10.0 ** k for k in range(-320, 309, 10))
    lines = ['// Generated by nig_reference.py with mpmath.', 'constexpr FixedReference fixed_references[] = {']
    for z in sorted(points):
        values = [float(v) for v in reference(z)]
        strings = [repr(v) if math.isfinite(v) else 'inf' for v in values]
        lines.append('    {' + repr(z) + ', {' + ', '.join(strings) + '}},')
    lines.append('};')
    Path(__file__).with_suffix('.inc').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--coefficients', action='store_true')
    args = parser.parse_args()
    coefficients() if args.coefficients else main()
