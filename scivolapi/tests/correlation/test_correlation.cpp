        CorrelationJet jet(model, sample);
        Buffers full(rows,d,n);
        const unsigned all = value | gradient | hessian | scores | terms | paths;
        watching = true;
        const auto result = jet.theta({ref.theta,d}, all, full.out, full.correlations);
        watching = false;
        check(result.status == Status::ok && result.valid == all, "full reference request");
        if (result.status != Status::ok) continue;
        compare(full.out.value, ref.value, ref.student, 0);
        for (std::size_t a=0;a<d;++a) compare(full.g[a],ref.g[a],ref.student,1);
        for (std::size_t a=0;a<d*d;++a) compare(full.h[a],ref.h[a],ref.student,2);
        for (std::size_t a=0;a<rows*d;++a) compare(full.s[a],ref.s[a],ref.student,3);
        for (std::size_t t=0;t<rows;++t) compare(full.l[t],ref.l[t],ref.student,4);
        double total=0;
        for(double v:full.l) total+=v;
        close(total,full.out.value,2e-13,"terms sum to value");
        for (std::size_t a=0;a<d;++a) {
            double sum=0;
            for(std::size_t t=0;t<rows;++t) sum+=full.s[t*d+a];
            close(sum,full.g[a],2e-13,"scores sum to gradient");
        }
        for (unsigned mask=1;mask<=all;++mask) {
            Buffers sparse(rows,d,n);
            watching=true;
            const auto r=jet.theta({ref.theta,d},mask,sparse.out,sparse.correlations);
            watching=false;
            check(r.status==Status::ok && r.valid==mask,"sparse request valid");
            close(sparse.out.value,(mask & value)?full.out.value:sentinel,0.,"sparse value");
            equal_outputs(sparse.g,full.g,mask & gradient,"sparse gradient");
            equal_outputs(sparse.h,full.h,mask & hessian,"sparse Hessian");
            equal_outputs(sparse.s,full.s,mask & scores,"sparse scores");
            equal_outputs(sparse.l,full.l,mask & terms,"sparse terms");
            equal_outputs(sparse.correlations,full.correlations,mask & paths,"sparse correlation paths");
            for(double v:sparse.unused) check(v==sentinel,"JetOutput.paths untouched");
        }
        std::vector<double> z(d), point(d), jac(d*d), curved(d*d);
        check(model.to_z({ref.theta,d},z),"inverse chart");
        model.to_theta(z,point);
        for(std::size_t a=0;a<d;++a) close(point[a],ref.theta[a],3e-14,"chart round trip");
        Buffers transformed(rows,d,n);
        watching=true;
        const auto zr=jet.z(z,value | gradient | hessian | terms,transformed.out);
