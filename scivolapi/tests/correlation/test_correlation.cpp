int main(int argc,char** argv)
{
    if(argc>1 && std::string(argv[1])=="--benchmark") benchmark();
    else {
        constants_test();
        references_test();
        domain_test();
        conditioning_test();
        size_test();
        check(allocations==0,"evaluations allocate nothing");
        const char* names[]={"value","gradient","Hessian","scores","terms"};
        for(int family=0;family<2;++family)
            for(int j=0;j<5;++j) std::printf("worst %s %s scaled error %.3g\n",family?"student_t":"normal",names[j],worst[family][j]);
        std::printf("JAX cases=%zu evaluations allocate=%zu failures=%d\n",std::size(references),allocations,failures);
    }
    return failures==0?0:1;
}
