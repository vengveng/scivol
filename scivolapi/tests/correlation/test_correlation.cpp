void quantiles_test()
{
    for (const auto& ref : quantile_references) {
        double normal, x, first, second;
        check(detail::quantile(DensityKind::normal, nullptr, ref.u, normal) == detail::ExpectationStatus::ok,
              "quantile Normal start");
        detail::StudentProbabilities data;
        data.u = {ref.u}; data.normal = {normal}; data.permutation = {0};
        data.identity_eta = {std::numeric_limits<double>::quiet_NaN()};
        double iterate, area;
        detail::StudentQuantileCache cache;
        cache.x = {&x, 1}; cache.first = {&first, 1}; cache.second = {&second, 1};
        cache.iterate = {&iterate, 1}; cache.area = {&area, 1};
        watching = true;
        const auto status = detail::student_quantiles(data, ref.eta, 2, cache);
        watching = false;
        check(status == detail::ExpectationStatus::ok, "implicit t quantile derivatives");
        const double r = 1.0 - 2.0 * ref.eta, root = std::sqrt(r);
        second = root * second - 2.0 * first / root - x / (r * root);
        first = root * first - x / root;
        x *= root;
        close(x, ref.x, 4e-12, "quantile mpmath value");
        close(first, ref.first, 5e-11, "quantile mpmath first");
        close(second, ref.second, 5e-11, "quantile mpmath second");
        for (int order : {0, 1}) {
            double sparse, sparse_first = sentinel, sparse_second = sentinel;
            cache.eta = std::numeric_limits<double>::quiet_NaN(); cache.order = -1;
            cache.x = {&sparse, 1}; cache.first = {&sparse_first, 1}; cache.second = {&sparse_second, 1};
            watching = true;
            const auto status = detail::student_quantiles(data, ref.eta, order, cache);
            watching = false;
            check(status == detail::ExpectationStatus::ok, "sparse quantile request");
            if (order >= 1) sparse_first = root * sparse_first - sparse / root;
            sparse *= root;
            close(sparse, x, 0.0, "sparse quantile bitwise value");
            close(sparse_first, order == 1 ? first : sentinel, 0.0, "sparse quantile first");
            close(sparse_second, sentinel, 0.0, "sparse quantile skips second");
        }
    }
}

void cumulative_quantiles_test()
{
    detail::StudentProbabilities data;
    data.identity_eta = {std::numeric_limits<double>::quiet_NaN()};
    for (const auto& ref : quantile_references)
        if (ref.eta == .1) data.u.push_back(ref.u);
    const std::size_t references = data.u.size();
    for (std::size_t i = 0; i < 4096; ++i) data.u.push_back((i + .5) / 4096.0);
    data.u.push_back(.5);
    data.u.push_back(.5);
    const std::size_t n = data.u.size();
    data.normal.resize(n);
    data.permutation.resize(n);
    std::iota(data.permutation.begin(), data.permutation.end(), 0);
    std::sort(data.permutation.begin(), data.permutation.end(), [&](std::size_t a, std::size_t b) {
        return std::min(data.u[a], 1.0 - data.u[a]) > std::min(data.u[b], 1.0 - data.u[b]);
    });
    for (std::size_t i = 0; i < n; ++i)
        check(detail::quantile(DensityKind::normal, nullptr, data.u[i], data.normal[i])
                  == detail::ExpectationStatus::ok, "batch Gaussian scores");
    std::vector<double> work(5 * n);
    detail::StudentQuantileCache cache;
    cache.x = {work.data(), n}; cache.first = {work.data() + n, n};
    cache.second = {work.data() + 2 * n, n}; cache.iterate = {work.data() + 3 * n, n};
    cache.area = {work.data() + 4 * n, n};
    for (double eta : {.1, .10001, .49, .4999, 1e-16, 0., 1e-6, .1}) {
        watching = true;
        const auto status = detail::student_quantiles(data, eta, 2, cache);
        watching = false;
        check(status == detail::ExpectationStatus::ok, "cumulative quantile correction");
        if (status != detail::ExpectationStatus::ok) continue;
        const double r = 1.0 - 2.0 * eta, root = std::sqrt(r);
        std::size_t i = 0;
        for (const auto& ref : quantile_references) {
            if (ref.eta != eta) continue;
            check(i < references, "batch reference index");
            close(root * cache.x[i], ref.x, 4e-12, "cumulative mpmath value");
            close(root * cache.first[i] - cache.x[i] / root, ref.first, 5e-11, "cumulative mpmath first");
            close(root * cache.second[i] - 2.0 * cache.first[i] / root - cache.x[i] / (r * root),
                  ref.second, 5e-11, "cumulative mpmath second");
            ++i;
        }
    }
}

void domain_test()
{
    for(auto [p,q]:{std::pair{0u,1u}, {1u,0u}, {9u,1u}, {1u,9u}})
        rejects([&]{CorrelationModel model({p,q});},"bad orders");
    CorrelationModel model({2,1,CorrelationDensity::student_t});
    check(model.dimension()==4,"dimension");
    check(model.parameter_names()==std::vector<std::string>{"a[1]","a[2]","b[1]","eta"},"parameter names");
    auto point=model.start();
    check(point==std::vector<double>{.025,.025,.90,.1},"start values");
    check(model.feasible(point) && model.evaluable(point),"start in domain");
    std::vector<double> lo(4),hi(4),v(1),jac(4),z(4);
    model.bounds(lo,hi);
    check(lo[0]==0. && lo[1]==0. && lo[2]==0. && lo[3]==0.,"bounds");
    for(std::size_t j=0;j<3;++j) check(std::isnan(hi[j]),"unbounded upper limits");
    check(hi[3]<.5,"open upper tail bound");
    check(model.constraint_count()==1,"one persistence constraint");
    model.constraints(point,v,jac);
    close(v[0],.05,3e-15,"persistence slack");
    check(jac==std::vector<double>{-1.,-1.,-1.,0.},"constraint Jacobian");
    point[0]=0.;
    check(model.feasible(point),"closed nonnegative face feasible");
    check(!model.to_z(point,z),"closed face has no finite chart inverse");
    point[0]=.1;point[1]=.1;point[2]=.8;
    check(!model.feasible(point),"strict persistence boundary");
    model.constraints(point,v,jac);
    close(v[0],0.,2e-16,"constraint on persistence boundary");
    point[0]=-.01;
    check(!model.feasible(point) && !model.evaluable(point),"negative coefficient rejected");
    point=model.start();point[3]=2.;
    check(!model.evaluable(point),"strict nu lower bound");
    point[3]=std::numeric_limits<double>::infinity();
    check(!model.evaluable(point),"nonfinite theta rejected");
    check(!model.evaluable({}),"wrong theta size rejected");

    const auto sample=model.prepare(eps_2,2,target_2);
    const auto estimated=model.prepare(eps_2,2);
    for(std::size_t a=0;a<4;++a) close(estimated.target[a],target_2[a],3e-15,"default target eps'eps/T");
    CorrelationJet jet(model,sample);
    check(&jet.model()==&model && &jet.sample()==&sample,"jet borrows model and sample");
    Buffers out(60,4,2);
    point=model.start();point[0]=-.01;
    check(jet.theta(point,value,out.out).status==Status::not_evaluable,"jet rejects coefficient hard bound");
    point=model.start();point[3]=2.;
    check(jet.theta(point,value,out.out).status==Status::not_evaluable,"jet rejects nu hard bound");
    point=model.start();
    check(jet.theta(point,0,out.out).status==Status::invalid_argument,"empty request");
    check(jet.theta(point,64,out.out).status==Status::invalid_argument,"unknown request");
    check(jet.theta(point,paths,out.out).status==Status::invalid_argument,"paths require correlation output");
    check(jet.z(point,scores,out.out).status==Status::invalid_argument,"z scores rejected");
    check(jet.z(point,paths,out.out).status==Status::invalid_argument,"z paths have no correlation output");
    JetOutput missing;
    check(jet.theta(point,gradient,missing).status==Status::invalid_argument,"wrong output size");
    std::vector<double> bad(eps_2,eps_2+120);
    bad[0]=std::numeric_limits<double>::quiet_NaN();
    rejects([&]{(void)model.prepare(bad,2);},"nonfinite eps");
    rejects([&]{(void)model.prepare(eps_2,0);},"zero series");
    rejects([&]{(void)model.prepare({eps_2,3},2);},"incomplete rows");
    rejects([&]{(void)model.prepare({eps_2,2},2);},"one row");
    const double singular[]={1.,1.,1.,1.}, indefinite[]={1.,2.,2.,1.};
    const double asymmetric[]={1.,.1,.2,1.}, nan[]={1.,0.,0.,std::numeric_limits<double>::quiet_NaN()};
    for(const double* target:{singular,indefinite,asymmetric,nan})
        rejects([&]{(void)model.prepare(eps_2,2,{target,4});},"invalid target");
    rejects([&]{(void)model.prepare(eps_2,2,{target_2,3});},"wrong target size");
    auto invalid=sample;invalid.target[0]=-1.;
    rejects([&]{CorrelationJet bad_jet(model,invalid);},"manually assembled invalid sample");
    point=model.start();point[0]=2.;point[1]=0.;point[2]=0.;
    check(jet.theta(point,value,out.out).status==Status::not_evaluable,"non-SPD recursion rejected");
    point=model.start();point[0]=point[1]=0.;point[2]=1.1;
    check(!model.feasible(point) && model.evaluable(point),"evaluability is wider than stationary domain");
    check(jet.theta(point,value,out.out).status==Status::ok,"nonstationary point with SPD recursion evaluable");
    std::vector<double> huge(4,1e308);
    const double identity[]={1.,0.,0.,1.};
    rejects([&] { (void)model.prepare(huge, 2, identity); }, "unrepresentable marginal probability rejected");
}

void conditioning_test()
{
    CorrelationModel model({2,2});
    const double eps[]={1.,2.,-.5,.2,1.3,-.7};
    const double target[]={2.,.4,.4,1.};
    const double theta[]={.1,.15,.2,.3};
    const auto sample=model.prepare(eps,2,target);
    CorrelationJet jet(model,sample);
    Buffers out(3,4,2);
    check(jet.theta(theta,paths,out.out,out.correlations).status==Status::ok,"conditioning paths");
    double q0[4],q1[4],q2[4];
    for(std::size_t i=0;i<2;++i)
        for(std::size_t j=0;j<2;++j) {
            const std::size_t a=i*2+j;
            q0[a]=target[a];
            q1[a]=.25*target[a]+.1*eps[i]*eps[j]+.2*q0[a];
        }
    for(std::size_t i=0;i<2;++i)
        for(std::size_t j=0;j<2;++j) {
            const std::size_t a=i*2+j;
            q2[a]=.25*target[a]+.1*eps[2+i]*eps[2+j]+.15*eps[i]*eps[j]+.2*q1[a]+.3*q0[a];
        }
    const double* matrices[]={q0,q1,q2};
    for(std::size_t t=0;t<3;++t)
        for(std::size_t i=0;i<2;++i)
            for(std::size_t j=0;j<2;++j)
                close(out.correlations[t*4+i*2+j],matrices[t][i*2+j]/std::sqrt(matrices[t][i*2+i]*matrices[t][j*2+j]),3e-15,"absent pre-sample lags");
}

