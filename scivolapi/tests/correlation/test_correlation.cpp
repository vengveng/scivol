constexpr double sentinel=12345.;
int failures=0;
double worst[2][5]{};

void check(bool ok,const char* message)
{
    if(!ok) { ++failures; std::printf("FAIL %s\n",message); }
}
void close(double actual,double expected,double tolerance,const char* message)
{
    const double error=std::abs(actual-expected)/std::max(1.,std::abs(expected));
    if(!std::isfinite(actual) || error>tolerance) {
        if(failures<30) std::printf("FAIL %s actual=%.17g expected=%.17g scaled=%.3g\n",message,actual,expected,error);
        ++failures;
    }
}
void compare(double actual,double expected,bool student,int derivative)
{
    const double error=std::abs(actual-expected)/std::max(1.,std::abs(expected));
    worst[student?1:0][derivative]=std::max(worst[student?1:0][derivative],error);
    close(actual,expected,1e-10,"independent JAX reference");
}
void equal_outputs(const std::vector<double>& actual,const std::vector<double>& full,bool requested,const char* message)
{
    for(std::size_t i=0;i<actual.size();++i) close(actual[i],requested?full[i]:sentinel,0.,message);
}

